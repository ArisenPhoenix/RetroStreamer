void configure_yuzu_archstreamer_controls(
    const YuzuUserProfile& profile,
    const std::vector<std::string>& sdl_guids) {
    if (sdl_guids.empty()) {
        std::cerr << "Warning: no ArchStreamer SDL GUIDs; Yuzu Controls left unchanged.\n";
        return;
    }

    const auto config_dir = profile.xdg_config_home / "yuzu";
    const auto config_path = config_dir / "qt-config.ini";
    const auto input_dir = config_dir / "input";
    std::filesystem::create_directories(input_dir);

    std::string contents;
    if (std::filesystem::exists(config_path)) {
        std::ifstream in(config_path);
        contents.assign(std::istreambuf_iterator<char>(in), std::istreambuf_iterator<char>());
    }
    if (contents.empty()) {
        ensure_yuzu_qt_config(profile, false, false, -1, 0);
        std::ifstream in(config_path);
        contents.assign(std::istreambuf_iterator<char>(in), std::istreambuf_iterator<char>());
    }

    set_qt_ini_group_value(contents, "Controls", "keyboard_enabled", "false");
    set_qt_ini_group_value(contents, "Controls", "keyboard_enabled\\default", "false");

    // Yuzu clears the SDL name-CRC (GUID bytes 2-3) before matching. Normalize here too
    // so callers that pass raw SDL_JoystickGetGUIDString values still work.
    const auto filter_guid = [](std::string guid) {
        if (guid.size() >= 8) {
            guid.replace(4, 4, "0000");
        }
        return guid;
    };

    for (std::size_t i = 0; i < sdl_guids.size() && i < 8; ++i) {
        if (sdl_guids[i].empty()) {
            continue;
        }
        const auto guid = filter_guid(sdl_guids[i]);
        // Same layout as ~/.config/yuzu/input/PS4.ini — selectable profiles plus active bindings.
        const auto profile_name =
            i == 0 ? std::string("ArchStreamer") : ("ArchStreamer_P" + std::to_string(i + 1));
        write_yuzu_input_profile(input_dir / (profile_name + ".ini"), guid);
        write_yuzu_player_sdl_controls(contents, static_cast<int>(i), guid);
    }

    std::ofstream out(config_path, std::ios::trunc);
    if (!out) {
        throw std::runtime_error("failed to write Yuzu Controls: " + config_path.string());
    }
    out << contents;
    std::cout
        << "Yuzu Controls: bound " << sdl_guids.size()
        << " ArchStreamer pad(s) via SDL GUID (+ input/ profile)\n";
}

std::vector<std::pair<std::string, std::string>> yuzu_launch_environment(
    const YuzuUserProfile& profile) {
    return {
        {"XDG_DATA_HOME", profile.xdg_data_home.string()},
        {"XDG_CONFIG_HOME", profile.xdg_config_home.string()},
        // gamescope headless often leaves the child without "focus"; without this SDL may
        // stop delivering joystick updates and Yuzu sees intermittent pad input.
        {"SDL_JOYSTICK_ALLOW_BACKGROUND_EVENTS", "1"},
    };
}

std::filesystem::path default_ryujinx_runtime_root() {
    if (const auto home = home_dir(); !home.empty()) {
#ifdef _WIN32
        const auto cache = archstreamer_cache_directory();
        if (!cache.empty()) {
            return std::filesystem::path{cache} / "ryujinx";
        }
        return home / "AppData" / "Local" / "archstreamer" / "ryujinx";
#else
        return home / ".local/share/archstreamer/ryujinx";
#endif
    }
    return std::filesystem::current_path() / "archstreamer-ryujinx";
}

bool ryujinx_runtime_available() {
#ifdef _WIN32
    const auto managed_binary = default_ryujinx_runtime_root() / "Ryujinx.exe";
#else
    const auto managed_binary = default_ryujinx_runtime_root() / "Ryujinx";
    const auto managed_appimage = default_ryujinx_runtime_root() / "Ryujinx.AppImage";
    if (std::filesystem::is_regular_file(managed_appimage)) {
        return true;
    }
#endif
    if (std::filesystem::is_regular_file(managed_binary)) {
        return true;
    }
    return find_source_ryujinx().has_value();
}

